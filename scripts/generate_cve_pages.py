def _hand_fields(mapping: dict):
    for tid, t in mapping.get("tests", {}).items():
        for key in ("sends",):
            yield f"tests.{tid}.{key}", t.get(key, "")
        for v in t.get("verdicts", []):
            yield f"tests.{tid}.verdicts.{v.get('outcome')}.when", v.get("when", "")
        for n in t.get("notes", []):
            yield f"tests.{tid}.notes", n
    for cve, c in mapping.get("cves", {}).items():
        for d in c.get("documented", []):
            yield f"cves.{cve}.documented.{d.get('test_id')}.why", d.get("why", "")
        for w in c.get("withheld", []):
            yield f"cves.{cve}.withheld.{w.get('test_id')}.reason", w.get("reason", "")
    for cve, e in mapping.get("excluded", {}).items():
        yield f"excluded.{cve}.reason", e.get("reason", "")


def validate(mapping: dict, root: Path = ROOT, *, citations=None, defined=None,
             catalog=None, harnesses=None) -> list[str]:
    """HEAD rules. The keyword arguments exist so a test can inject derived data."""
    fails: list[str] = []

    def fail(rule: str, detail: str) -> None:
        fails.append(f"[{rule}] {detail}")

    universe, pairs = citations if citations is not None else source_citations(root)
    defined = defined if defined is not None else defined_test_ids(root)
    catalog = catalog if catalog is not None else catalog_entries(root)
    harnesses = harnesses if harnesses is not None else cli_harnesses(root)

    cves = mapping.get("cves") or {}
    excluded = mapping.get("excluded") or {}
    tests = mapping.get("tests") or {}

    sha = str(mapping.get("pinned_commit", ""))
    if not re.fullmatch(r"[0-9a-f]{40}", sha):
        fail("pin_format", f"pinned_commit must be a full 40-char SHA, got {sha!r}")
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(mapping.get("retrieved", ""))):
        fail("retrieved", "retrieved must be an ISO date")

    # r1: every cited CVE is accounted for, once, and nothing stale is listed.
    for cve in sorted(universe):
        if cve not in cves and cve not in excluded:
            fail("r1_unaccounted", f"{cve} is cited in protocol_tests/ but is neither "
                 "documented under `cves` nor listed under `excluded` with a reason")
    for cve in sorted(set(cves) & set(excluded)):
        fail("r1_both", f"{cve} is both documented and excluded")
    for cve in sorted((set(cves) | set(excluded)) - universe):
        fail("r1_stale", f"{cve} is in the mapping but no longer cited in protocol_tests/")
    for cve, e in excluded.items():
        if not (e or {}).get("reason"):
            fail("r1_reason", f"excluded {cve} has no reason")

    # r2: the documented/withheld split covers exactly the source pairs.
    for cve, c in cves.items():
        documented = [d["test_id"] for d in c.get("documented") or []]
        withheld = [w["test_id"] for w in c.get("withheld") or []]
        if not documented:
            fail("r2_empty", f"{cve} documents no test; exclude it instead")
        source_side = set(pairs.get(cve, {}))
        for tid in documented:
            if tid not in source_side:
                fail("r2_unpaired", f"{cve} documents {tid}, but no source in protocol_tests/ "
                     "pairs that test with this CVE")
        for tid in sorted(source_side - set(documented) - set(withheld)):
            fail("r2_unaccounted_pair", f"source pairs {cve} with {tid}; document it or "
                 "withhold it with a reason")
        for tid in sorted(set(documented) & set(withheld)):
            fail("r2_both", f"{cve}/{tid} is both documented and withheld")
        for w in c.get("withheld") or []:
            if not w.get("reason"):
                fail("r2_reason", f"{cve} withholds {w.get('test_id')} with no reason")
        for d in c.get("documented") or []:
            if not d.get("why"):
                fail("r2_why", f"{cve}/{d['test_id']} has no `why`")
            if d["test_id"] not in tests:
                fail("r2_test_entry", f"{cve} documents {d['test_id']}, which has no "
                     "entry under `tests`")
        for key in ("product", "summary", "summary_source", "affected", "fixed", "cvss",
                    "cwe", "published", "cna"):
            if not c.get(key):
                fail("r4_fact", f"{cve} is missing `{key}`")
        if not isinstance(c.get("summary_is_excerpt"), bool):
            fail("r4_fact", f"{cve}: summary_is_excerpt must be true or false")
        if "kev" not in c:
            fail("r4_fact", f"{cve} must state `kev` (null when not listed)")
        if c.get("ghsa") is None and not c.get("ghsa_note"):
            fail("r4_fact", f"{cve} has no GHSA entry and no `ghsa_note` saying so")

    # r3: every test ID exists, in its named module, and in the catalog verbatim.
    used = {d["test_id"] for c in cves.values() for d in c.get("documented") or []}
    for tid in sorted(set(tests) - used):
        fail("r3_orphan", f"tests.{tid} is not documented under any CVE")
    all_ids = used | set(tests) | {w["test_id"] for c in cves.values()
                                   for w in c.get("withheld") or []}
    for tid in sorted(all_ids):
        if tid not in defined:
            fail("r3_defined", f"{tid} is not defined anywhere in protocol_tests/")
        if tid not in catalog:
            fail("r3_catalog", f"{tid} does not appear in HARNESS_TEST_CATALOG.md")
    for tid, t in tests.items():
        mod = t.get("module", "")
        if tid in defined and mod not in defined[tid]:
            fail("r3_module", f"{tid} is not defined in {mod}")
        if not (root / mod).is_file():
            fail("r3_module", f"{tid}: {mod} does not exist")
            continue
        text = (root / mod).read_text(encoding="utf-8", errors="replace")
        if def_line(text, t.get("symbol", "")) is None:
            fail("r3_symbol", f"{tid}: def {t.get('symbol')} not found in {mod}")
        if t.get("observes") not in OBSERVES:
            fail("r3_observes", f"{tid}: observes must be one of {sorted(OBSERVES)}")
        if not t.get("cites"):
            fail("r3_cites", f"{tid} cites no line of its own source")
        outcomes = [v.get("outcome") for v in t.get("verdicts") or []]
        if "PASS" not in outcomes or "FAIL" not in outcomes:
            fail("r3_verdicts", f"{tid} must describe PASS and FAIL")
        for o in outcomes:
            if o not in OUTCOMES:
                fail("r3_verdicts", f"{tid}: unknown outcome {o!r}")

        # r5: the run line names a real harness and only flags it accepts.
        run = t.get("run", "")
        try:
            toks = shlex.split(run)
        except ValueError as e:
            fail("r5_run", f"{tid}: run line does not parse: {e}")
            continue
        if toks[:2] != ["agent-security", "test"] or len(toks) < 3:
            fail("r5_run", f"{tid}: run line must start `agent-security test <harness>`")
            continue
        harness = toks[2]
        if harness not in harnesses:
            fail("r5_run", f"{tid}: harness {harness!r} is not registered in cli.py")
            continue
        hmod = root / harnesses[harness]
        if hmod.is_file() and hmod.resolve() != (root / mod).resolve():
            fail("r5_run", f"{tid}: harness {harness!r} runs {harnesses[harness]}, not {mod}")
        htext = hmod.read_text(encoding="utf-8") if hmod.is_file() else ""
        for flag in (x.split("=")[0] for x in toks if x.startswith("--")):
            if not re.search(r'add_argument\(\s*["\']' + re.escape(flag) + r'["\']', htext):
                fail("r5_flag", f"{tid}: {harnesses[harness]} defines no {flag} option")

    # r6: hand-written text stays factual.
    for where, text in _hand_fields(mapping):
        low = (text or "").lower()
        for phrase in PROHIBITED:
            if re.search(r"\b" + re.escape(phrase) + r"\b", low):
                fail("r6_language", f"{where} contains {phrase!r}")
    return fails


def validate_pinned(mapping: dict, root: Path = ROOT) -> list[str]:
    """Pinned rules. Caller must first establish the pinned commit is present."""
    fails: list[str] = []
    sha = mapping["pinned_commit"]
    if _git(root, "merge-base", "--is-ancestor", sha, "HEAD").returncode != 0:
        fails.append(f"[pin_ancestor] {sha[:12]} is not an ancestor of HEAD; "
                     "permalinks into it would not describe this branch's history")
    for tid, t in (mapping.get("tests") or {}).items():
        blob = pinned_blob(root, sha, t["module"])
        if blob is None:
            fails.append(f"[pin_module] {tid}: {t['module']} does not exist at {sha[:12]}")
            continue
        text = blob.decode("utf-8", errors="replace")
        if def_line(text, t["symbol"]) is None:
            fails.append(f"[pin_symbol] {tid}: def {t['symbol']} not at {sha[:12]}")
        for q in t.get("cites") or []:
            if locate(text, q) is None:
                fails.append(f"[pin_quote] {tid}: cited text not verbatim in {t['module']} "
                             f"at {sha[:12]}: {q[:70]!r}")
        for v in t.get("verdicts") or []:
            if not v.get("quote"):
                continue
            vmod = v.get("module", t["module"])
            vblob = pinned_blob(root, sha, vmod)
            vtext = vblob.decode("utf-8", errors="replace") if vblob is not None else ""
            if locate(vtext, v["quote"]) is None:
                fails.append(f"[pin_quote] {tid} {v['outcome']}: not verbatim in {vmod} at "
                             f"{sha[:12]}: {v['quote'][:70]!r}")
    return fails


