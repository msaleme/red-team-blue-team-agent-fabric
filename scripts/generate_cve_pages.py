def _permalink(mapping: dict, rel: str, line: int | None = None) -> str:
    url = f"{mapping['repository']}/blob/{mapping['pinned_commit']}/{rel}"
    return f"{url}#L{line}" if line else url


def _src_ref(mapping: dict, rel: str, line: int | None) -> str:
    label = f"{rel}:{line}" if line else rel
    return f"[`{label}`]({_permalink(mapping, rel, line)})"


def _quote_block(text: str) -> str:
    return "> " + _norm(text)


def _title(cve: str, c: dict) -> str:
    ids = ", ".join(d["test_id"] for d in c["documented"])
    return f"Testing for {cve} ({c['product']}): {ids}"


def render_cve(mapping: dict, cve: str, root: Path, catalog: dict[str, str]) -> str:
    c = mapping["cves"][cve]
    sha = mapping["pinned_commit"]
    short = sha[:7]
    date = mapping["retrieved"]
    src = mapping["sources"]
    out: list[str] = [GENERATED_BANNER, "", f"# {_title(cve, c)}", ""]
    out += [f"Source citations below are pinned to commit [`{short}`]"
            f"({mapping['repository']}/tree/{sha}). Vulnerability facts were retrieved "
            f"from the primary sources listed at the end on {date}. "
            "[All CVE pages](README.md).", ""]

    out += ["## The vulnerability", ""]
    out += [_quote_block(c["summary"]), ""]
    lead = "Excerpt from" if c["summary_is_excerpt"] else "From"
    out += [f"{lead} the {c['summary_source']} description of {cve}"
            f" ({src['nvd_page']}{cve}), retrieved {date}.", ""]
    out += ["| Field | Value | Source |", "|---|---|---|"]
    out.append(f"| Product | {c['product']} ({c['component']}) | NVD |")
    out.append(f"| Published | {c['published']} | NVD |")
    out.append(f"| NVD status | {c['nvd_status']} | NVD |")
    out.append(f"| Assigning CNA | {c['cna']} | NVD |")
    for a in c["affected"]:
        out.append(f"| Affected | {a['value']} | {a['source']} |")
    for f in c["fixed"]:
        out.append(f"| Fixed | {f['value']} | {f['source']} |")
    for v in c["cvss"]:
        out.append(f"| CVSS | {v['score']} {v['severity']} (CVSS {v['version']}, "
                   f"`{v['vector']}`) | {v['source']}, scored by {v['scored_by']} |")
    for w in c["cwe"]:
        out.append(f"| CWE | {w['id']} | {w['source']}, from {w['scored_by']} |")
    kev = c.get("kev")
    if kev:
        out.append(f"| CISA KEV | Listed. dateAdded {kev['date_added']}, dueDate "
                   f"{kev['due_date']}, knownRansomwareCampaignUse "
                   f"{kev['known_ransomware_campaign_use']} | CISA KEV catalog "
                   f"{mapping['kev_catalog_version']} |")
    else:
        out.append(f"| CISA KEV | Not listed in catalog version "
                   f"{mapping['kev_catalog_version']} as of {date} | CISA KEV catalog |")
    g = c.get("ghsa")
    if g:
        state = "reviewed" if g["reviewed"] else "unreviewed"
        out.append(f"| GitHub advisory | [{g['id']}](https://github.com/advisories/{g['id']})"
                   f" ({state}) | GitHub Advisory Database |")
    else:
        out.append(f"| GitHub advisory | {c['ghsa_note']} | GitHub Advisory Database |")
    out.append("")

    out += ["## ASH tests that exercise this class", ""]
    for d in c["documented"]:
        tid = d["test_id"]
        t = mapping["tests"][tid]
        text = pinned_blob(root, sha, t["module"]).decode("utf-8", errors="replace")
        dl = def_line(text, t["symbol"])
        where = "the target" if t["observes"] == "target" else \
            "the machine running the harness, not the target"
        out += [f"### {tid}: {catalog.get(tid, '')}", ""]
        out += [f"Defined at {_src_ref(mapping, t['module'], dl)} (`{t['symbol']}`). "
                f"Observes {where}.", ""]
        out += [d["why"], ""]
        out += ["The test's own source:", ""]
        for q in t["cites"]:
            ql = locate_in(text, q, t["symbol"])
            out += [_quote_block(q), ">", f"> {_src_ref(mapping, t['module'], ql)}", ""]
        out += [f"**What it sends.** {t['sends']}", ""]
        out += ["**Run it** against a target you are authorised to test:", "", "```sh",
                t["run"], "```", ""]
        out += ["**Verdicts.**", ""]
        for v in t["verdicts"]:
            line = f"- **{v['outcome']}**: {v['when']}"
            if v.get("quote"):
                vmod = v.get("module", t["module"])
                vtext = pinned_blob(root, sha, vmod).decode("utf-8", errors="replace")
                sym = t["symbol"] if vmod == t["module"] else None
                line += f" Source: {_src_ref(mapping, vmod, locate_in(vtext, v['quote'], sym))}"
                out += [line, f"  > {_norm(v['quote'])}"]
            else:
                out.append(line)
        out.append("")
        if t.get("notes"):
            out += ["**Read before relying on a verdict.**", ""]
            out += [f"- {n}" for n in t["notes"]]
            out.append("")

    if c.get("withheld"):
        out += ["## Tests the source pairs with this CVE that are not documented here", ""]
        for w in c["withheld"]:
            out.append(f"- **{w['test_id']}** ({catalog.get(w['test_id'], '')}): {w['reason']}")
        out.append("")

    out += ["## Scope", "",
            "These tests exercise the vulnerability class against a target you are "
            "authorised to test. They are not an exploit for the vendor product, they "
            "do not check the product's version, and a result does not establish that a "
            "given deployment is or is not affected by this CVE. What each outcome means "
            "in general is fixed in [RESULT-SEMANTICS.md](../RESULT-SEMANTICS.md).", ""]

    out += ["## Sources", "", f"All retrieved {date}.", ""]
    out.append(f"- NVD: {src['nvd_page']}{cve} (API: {src['nvd_api']}{cve})")
    if g:
        out.append(f"- GitHub Advisory Database: https://github.com/advisories/{g['id']} "
                   f"(API: {src['ghsa_api']}{cve})")
    else:
        out.append(f"- GitHub Advisory Database query: {src['ghsa_api']}{cve} (no result)")
    out.append(f"- CISA Known Exploited Vulnerabilities catalog, version "
               f"{mapping['kev_catalog_version']}: {src['kev_feed']}")
    for r in c.get("references") or []:
        out.append(f"- {r}")
    out.append("")
    return "\n".join(out)


def render_index(mapping: dict, root: Path, catalog: dict[str, str]) -> str:
    sha = mapping["pinned_commit"]
    date = mapping["retrieved"]
    cves = mapping["cves"]
    out = [GENERATED_BANNER, "", "# CVE to ASH test index", ""]
    out += ["Publicly disclosed CVEs that the harness source cites, and the tests that "
            "exercise each one's vulnerability class. Each page has the vulnerability "
            "facts from primary sources, the test's own source lines, the command to run "
            "it, and what each verdict means.", ""]
    out += ["A test here checks a vulnerability class against a target you are "
            "authorised to test. It is not a vendor exploit and a result does not "
            "establish that a deployment is or is not affected.", ""]
    out += ["| | |", "|---|---|",
            f"| Repository | `{mapping['repository']}` |",
            f"| Revision all citations are pinned to | `{sha}` |",
            f"| Vulnerability facts retrieved | {date} (NVD, GitHub Advisory Database, "
            f"CISA KEV catalog {mapping['kev_catalog_version']}) |",
            "| Generated by | `scripts/generate_cve_pages.py` from "
            "[`cve-test-mapping.yaml`](cve-test-mapping.yaml) |", ""]
    modules = sorted({t["module"] for t in mapping["tests"].values()})
    out += ["SHA-256 of the files cited, at that revision:", "", "```"]
    for rel in modules:
        out.append(f"{hashlib.sha256(pinned_blob(root, sha, rel)).hexdigest()}  {rel}")
    out += ["```", ""]

    out += ["## Documented", ""]
    out += ["| CVE | Product | ASH tests | CVSS (source) | CISA KEV |", "|---|---|---|---|---|"]
    for cve in sorted(cves, key=_cve_key):
        c = cves[cve]
        ids = ", ".join(d["test_id"] for d in c["documented"])
        cv = "; ".join(f"{v['score']} {v['severity']}, CVSS {v['version']}, {v['scored_by']}"
                       for v in c["cvss"])
        kev = f"Listed {c['kev']['date_added']}" if c.get("kev") else "Not listed"
        out.append(f"| [{cve}]({cve}.md) | {c['product']} | {ids} | {cv} | {kev} |")
    out.append("")

    withheld = [(cve, w) for cve in sorted(cves, key=_cve_key)
                for w in cves[cve].get("withheld") or []]
    if withheld:
        out += ["## Tests cited beside a documented CVE but not documented for it", ""]
        out += ["| CVE | Test | Reason |", "|---|---|---|"]
        for cve, w in withheld:
            out.append(f"| {cve} | {w['test_id']} | {w['reason']} |")
        out.append("")

    out += ["## CVEs cited in the source without a page", ""]
    out += ["| CVE | Reason |", "|---|---|"]
    for cve in sorted(mapping.get("excluded") or {}, key=_cve_key):
        out.append(f"| {cve} | {mapping['excluded'][cve]['reason']} |")
    out.append("")

    out += ["## How this list is kept honest", "",
            "The CVEs and their test pairings are derived from `protocol_tests/`, not "
            "written by hand. `python scripts/generate_cve_pages.py --check`, run by "
            "`testing/test_cve_pages_are_current.py`, fails when the source cites a CVE "
            "the mapping does not account for, when a test paired with a CVE in source "
            "is neither documented nor withheld with a reason, when a test ID does not "
            "exist or is missing from [HARNESS_TEST_CATALOG.md](../../HARNESS_TEST_CATALOG.md), "
            "when a quoted source line is not verbatim at the pinned revision, or when "
            "these pages differ from regenerated output.", "",
            "Vulnerability facts cannot be derived from this repository. They were "
            "retrieved from the sources named on each page and are re-retrieved, not "
            "edited, when updated.", ""]
    return "\n".join(out)


def _cve_key(cve: str) -> tuple[int, int]:
    _, year, num = cve.split("-")
    return int(year), int(num)


def render_all(mapping: dict, root: Path = ROOT) -> dict[Path, str]:
    catalog = catalog_entries(root)
    out = out_dir(root)
    pages = {out / "README.md": render_index(mapping, root, catalog)}
    for cve in mapping["cves"]:
        pages[out / f"{cve}.md"] = render_cve(mapping, cve, root, catalog)
    return pages


def drift(mapping: dict, root: Path = ROOT) -> list[str]:
    fails = []
    expected = render_all(mapping, root)
    for path, text in expected.items():
        rel = path.relative_to(root)
        if not path.is_file():
            fails.append(f"[drift] {rel} is missing; run scripts/generate_cve_pages.py")
        elif path.read_text(encoding="utf-8") != text:
            fails.append(f"[drift] {rel} differs from freshly generated output")
    for path in out_dir(root).glob("CVE-*.md"):
        if path not in expected:
            fails.append(f"[drift] {path.relative_to(root)} has no entry in the mapping")
    return fails


def load(root: Path = ROOT) -> dict:
    return yaml.safe_load(mapping_path(root).read_text(encoding="utf-8"))


def _require_checkout(root: Path) -> None:
    """One line naming the missing checkout resource, exit 2, no traceback."""
    for rel in ("/".join(MAPPING_PARTS), "HARNESS_TEST_CATALOG.md", "protocol_tests/cli.py",
                ".git"):
        if not (root / rel).exists():
            print(f"generate_cve_pages.py: checkout-only resource missing: {rel} (expected "
                  f"under {root}). This generator reads the CVE mapping, the test catalog "
                  "and git history, which the wheel does not ship; run it from a clone.",
                  file=sys.stderr)
            raise SystemExit(2)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="validate and compare with the pages on disk; write nothing")
    args = ap.parse_args(argv)
    _require_checkout(ROOT)
    mapping = load()
    fails = validate(mapping)
    sha = mapping.get("pinned_commit", "")
    pinned_ok = pin_available(ROOT, sha)
    if not pinned_ok and not is_shallow(ROOT):
        fails.append(f"[pin_missing] pinned_commit {sha[:12]} is not in this repository")
    if pinned_ok:
        fails += validate_pinned(mapping)
    if fails:
        print(f"FAIL - {len(fails)} rule violation(s):\n")
        for f in fails:
            print(f"  {f}")
        return 1
    if not pinned_ok:
        # Exit 2, the repository's "could not check" code: the HEAD rules held,
        # but a green exit here would read as the pages having been verified.
        print("HEAD rules pass. Pinned rules NOT RUN: shallow clone, pinned commit absent. "
              "Not a pass for the pages; run with full history.")
        return 2
    if args.check:
        d = drift(mapping)
        if d:
            print(f"FAIL - {len(d)} page(s) drifted:\n")
            for f in d:
                print(f"  {f}")
            return 1
        print(f"PASS - {len(mapping['cves'])} CVE pages, {len(mapping['excluded'])} "
              "excluded, all rules hold.")
        return 0
    for path, text in render_all(mapping).items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
