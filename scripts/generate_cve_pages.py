#!/usr/bin/env python3
"""Generate docs/cve/ from docs/cve/cve-test-mapping.yaml, and check it has not drifted.

    python scripts/generate_cve_pages.py            # write the pages
    python scripts/generate_cve_pages.py --check    # exit 1 on any rule violation or drift

Which CVEs get a page is not decided by hand. `source_citations()` scans
`protocol_tests/` for every CVE identifier and for the test IDs each one is
cited beside, and `validate()` fails unless the mapping accounts for all of
them: every cited CVE is documented or excluded with a reason, and every test
the source pairs with a documented CVE is documented or withheld with a reason.
A documented test that the source does not pair with that CVE fails too, so a
page cannot claim coverage the code does not state.

Two groups of rules, because they need different things:

  HEAD rules      the working tree only. Run everywhere, including the
                  shallow checkout CI uses for the main test job.
  pinned rules    need `pinned_commit` in the object store: every quoted line is
                  checked verbatim against the module at that commit, line
                  anchors are computed there, and the pages are regenerated and
                  compared. In a shallow clone they report that they could not
                  run; the `pinned-provenance` CI job has full history and runs
                  them for real.

Checkout-only: it reads docs/cve/, HARNESS_TEST_CATALOG.md and git history,
none of which the wheel ships. Run from a clone; anywhere else it exits 2 with
one line naming the missing resource.
"""
