def _checkout_root() -> Path:
    """The git checkout this is run from. Not a path climbed from __file__: in an
    installed wheel that is site-packages, which has no docs/ and no history."""
    out = subprocess.run(("git", "rev-parse", "--show-toplevel"), capture_output=True,
                         text=True, check=False)
    top = out.stdout.strip()
    return Path(top) if out.returncode == 0 and top else Path.cwd()


ROOT = _checkout_root()
MAPPING_PARTS = ("docs", "cve", "cve-test-mapping.yaml")


def out_dir(root: Path) -> Path:
    return root / "docs" / "cve"


def mapping_path(root: Path) -> Path:
    return root.joinpath(*MAPPING_PARTS)

CVE_RE = re.compile(r"\bCVE-\d{4}-\d{4,7}\b")
# Same two conventions scripts/validate_owasp_agentic_mapping.py and
# scripts/count_tests.py use for "this module defines that test".
TEST_ID_ASSIGN = re.compile(r'test_id\s*=\s*["\']([A-Z][A-Z0-9]*-\d{3})["\']')
TEST_ID_HELPER = re.compile(r'(?:self\._test_\w+|_test_\w+)\(\s*["\']([A-Z][A-Z0-9]*-\d{3})["\']')
BARE_ID = re.compile(r"\b([A-Z][A-Z0-9]*-\d{3})\b")

OUTCOMES = ("PASS", "FAIL", "INCONCLUSIVE")
OBSERVES = {"target", "local"}
#: Hand-written fields must not carry these. Quotes from the source are exempt:
#: they are the source's words, and checked verbatim instead.
PROHIBITED = ("certified", "certification", "compliant", "compliance",
              "guarantee", "fully mitigates", "is not vulnerable", "is vulnerable",
              "stolen", "best-in-class", "industry-leading")

GENERATED_BANNER = ("<!-- Generated by scripts/generate_cve_pages.py from "
                    "docs/cve/cve-test-mapping.yaml. Do not edit by hand. -->")


