def _git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(("git", *args), cwd=root, capture_output=True, check=False)


def pin_available(root: Path, sha: str) -> bool:
    return _git(root, "cat-file", "-e", f"{sha}^{{commit}}").returncode == 0


def is_shallow(root: Path) -> bool:
    out = _git(root, "rev-parse", "--is-shallow-repository")
    return out.stdout.decode().strip() == "true"


def pinned_blob(root: Path, sha: str, rel: str) -> bytes | None:
    out = _git(root, "show", f"{sha}:{rel}")
    return out.stdout if out.returncode == 0 else None


def symbol_span(text: str, symbol: str) -> tuple[int, int] | None:
    """(first, last) line of the function named `symbol`, or None."""
    for node in ast.walk(ast.parse(text)):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == symbol:
            return node.lineno, node.end_lineno
    return None


def locate_in(text: str, quote: str, symbol: str | None) -> int | None:
    """Prefer the occurrence inside `symbol`'s own body, so a verdict string is
    anchored to the test that emits it rather than to a comment quoting it."""
    span = symbol_span(text, symbol) if symbol else None
    if span:
        lines = text.splitlines()
        inner = locate("\n".join(lines[span[0] - 1:span[1]]), quote)
        if inner is not None:
            return inner + span[0] - 1
    return locate(text, quote)


def locate(text: str, quote: str) -> int | None:
    """1-based line where `quote` starts in `text`, whitespace-normalised; else None."""
    target = _norm(quote)
    if not target:
        return None
    # Normalised text, with the source line of every normalised character.
    chars: list[str] = []
    where: list[int] = []
    pending_space = False
    for lineno, line in enumerate(text.splitlines(), start=1):
        for ch in line:
            if ch.isspace():
                pending_space = bool(chars)
                continue
            if pending_space:
                chars.append(" ")
                where.append(lineno)
                pending_space = False
            chars.append(ch)
            where.append(lineno)
        pending_space = bool(chars)
    i = "".join(chars).find(target)
    return where[i] if i >= 0 else None


def def_line(text: str, symbol: str) -> int | None:
    m = re.search(r"^[ \t]*def\s+" + re.escape(symbol) + r"\s*\(", text, re.M)
    return text[:m.start()].count("\n") + 1 if m else None


