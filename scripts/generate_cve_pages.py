def _norm(text: str) -> str:
    return " ".join(text.split())


def source_citations(root: Path = ROOT) -> tuple[set[str], dict[str, dict[str, set[str]]]]:
    """(every CVE cited in protocol_tests/, {cve: {test_id: {module, ...}}}).

    A CVE and a test ID are paired when both appear in the source of one
    function, which is how every CVE-specific test here states what it covers
    (a `cve=` field, a docstring, or its verdict text).

    Fallback for a family whose tests do not name the CVE themselves: when a
    module's docstring cites a CVE that no function in that module pairs, it is
    paired with the test IDs the module and class docstrings name. That is how
    workspace_trust_harness.py states it. A CVE the docstrings cite only as
    context, with no test ID beside it, pairs with nothing and must be excluded.
    """
    universe: set[str] = set()
    pairs: dict[str, dict[str, set[str]]] = {}

    def add(cve: str, tid: str, rel: str) -> None:
        pairs.setdefault(cve, {}).setdefault(tid, set()).add(rel)

    for path in sorted((root / "protocol_tests").rglob("*.py")):
        text = path.read_text(encoding="utf-8", errors="replace")
        cited = set(CVE_RE.findall(text))
        if not cited:
            continue
        universe |= cited
        rel = str(path.relative_to(root))
        lines = text.splitlines()
        tree = ast.parse(text)
        paired_here: set[str] = set()
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            seg = "\n".join(lines[node.lineno - 1:node.end_lineno])
            cves = set(CVE_RE.findall(seg))
            tids = set(TEST_ID_ASSIGN.findall(seg))
            for cve in cves:
                for tid in tids:
                    add(cve, tid, rel)
                    paired_here.add(cve)
        docs = ast.get_docstring(tree) or ""
        class_docs = " ".join(ast.get_docstring(n) or "" for n in ast.walk(tree)
                              if isinstance(n, ast.ClassDef))
        defined = set(TEST_ID_ASSIGN.findall(text)) | set(TEST_ID_HELPER.findall(text))
        named = {t for t in BARE_ID.findall(docs + " " + class_docs) if t in defined}
        for cve in set(CVE_RE.findall(docs)) - paired_here:
            for tid in named:
                add(cve, tid, rel)
    return universe, pairs


def defined_test_ids(root: Path = ROOT) -> dict[str, set[str]]:
    """{test_id: {module, ...}} from scripts/count_tests.py, the canonical counter.

    Deriving it separately here would let this guard and the published test
    count disagree about which tests exist.
    """
    sys.path.insert(0, str(root / "scripts"))
    import count_tests  # noqa: E402
    idx: dict[str, set[str]] = {}
    for filename, ids in count_tests.module_ids().items():
        for tid in ids:
            idx.setdefault(tid, set()).add(f"protocol_tests/{filename}")
    return idx


def catalog_entries(root: Path = ROOT) -> dict[str, str]:
    """{test_id: name} from HARNESS_TEST_CATALOG.md rows `ID | Name | path:line`."""
    out: dict[str, str] = {}
    for line in (root / "HARNESS_TEST_CATALOG.md").read_text(encoding="utf-8").splitlines():
        m = re.match(r"^([A-Z][A-Z0-9]*-\d{3}) \| (.+?) \| (\S+)$", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def cli_harnesses(root: Path = ROOT) -> dict[str, str]:
    """{harness name: module path} from the HARNESSES registry in cli.py."""
    text = (root / "protocol_tests" / "cli.py").read_text(encoding="utf-8")
    out = {}
    for m in re.finditer(r'^\s{4}"([a-z0-9-]+)":\s*\{\s*\n\s*"module":\s*"([\w.]+)"', text, re.M):
        out[m.group(1)] = m.group(2).replace(".", "/") + ".py"
    return out


